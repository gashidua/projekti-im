-- Ekzekutoje në Supabase SQL Editor për tabelën publike të eventeve.
create table if not exists public.eventet (
  id bigint generated by default as identity primary key,
  titulli text not null unique,
  data date not null,
  ora time not null,
  vendi text not null,
  kategoria text not null check (
    kategoria in ('Muzikë', 'Teatër', 'Ceremoni', 'Lojëra', 'Sport')
  ),
  pershkrimi text not null
);

alter table public.eventet enable row level security;
grant select on public.eventet to anon;

drop policy if exists "Eventet mund të lexohen publikisht" on public.eventet;
create policy "Eventet mund të lexohen publikisht"
  on public.eventet
  for select
  to anon
  using (true);

